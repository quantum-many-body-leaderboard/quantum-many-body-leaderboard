const BEGIN = "<!-- BEGIN LEADERBOARD (generated by scripts/readme_table.mjs - do not edit) -->";
const END = "<!-- END LEADERBOARD -->";
// The VarBench credit under "## Citing" states how many rows are imported; the count is
// rewritten on every build so it cannot go stale. No HTML-comment markers: a line that
// starts with <!-- is an HTML block on GitHub, which then renders no markdown in it.
const VB_COUNT = /\d+ of QMBL’s \d+ rows \(\d+ %\)/;

// Physics convention: one significant digit of uncertainty in parentheses, and the
// energy quoted to exactly that decimal place, so the table shows no digits past the
// error bar.
export function quote(energy, sigma) {
  // A stated sigma of exactly 0 is how the upstream tables write "deterministic" on an
  // exact diagonalization. There is no last digit for it to qualify, and taking its
  // logarithm asks for infinitely many decimals, so it is quoted like a row with none.
  // Without a sigma the energy is quoted to at most 7 decimals with the padding zeros
  // dropped, so a printed -0.4988 is not shown as -0.4988000.
  if (sigma == null || !(sigma > 0)) {
    const text = energy.toFixed(7).replace(/\.?0+$/, "");
    return { text, decimals: text.split(".")[1]?.length ?? 0 };
  }
  const rounded = Number(sigma.toPrecision(1));
  const decimals = Math.max(0, -Math.floor(Math.log10(rounded)));
  const digit = Math.round(rounded * 10 ** decimals);
  return { text: `${energy.toFixed(decimals)}(${digit})`, decimals };
}

// Method strings run to 60+ characters; they are cut at a space or comma, as a cut
// mid-word reads as a typo.
export function shorten(method, max) {
  if (method.length <= max) return method;
  const cut = method.slice(0, max);
  const at = Math.max(cut.lastIndexOf(" "), cut.lastIndexOf(","));
  return (at > max * 0.6 ? cut.slice(0, at) : cut).replace(/[,(]$/, "") + "...";
}

// Markers shown against a number, in precedence order. A row carrying no error metric
// at all gets the circle and nothing else: a sampled row with no variance has no sigma
// either, so the dagger would add nothing.
export function marks(r) {
  if (noErrorMetrics(r)) return " &#9675;";
  if (isSampled(r) && r.sigma == null) return " &dagger;";
  return "";
}

// Every instance is listed, one collapsed table per model, and the reader clicks through
// them; the frontier table (views.mjs) is rendered only on the site. Those labels are built
// from the instance itself, so anything added to data/ appears without a hand-written entry.
export const MODELS = [
  ["Heisenberg", "Heisenberg"],
  ["J1J2", "J1-J2"],
  ["Hubbard", "Hubbard"],
  ["tV", "Spinless t-V"],
  ["TFIsing", "Transverse-field Ising"],
  ["Impurity", "Impurity"],
  ["HEG3D", "Electron gas, 3D"],
  ["HEG2D", "Electron gas, 2D"],
];

// Boundary codes as defined in vendor/varbench/lattice.md. Periodic is the default and
// goes unsaid, as in the frontier labels.
export const BOUNDARY = { O: "open", PO: "periodic/open", PA: "periodic/antiperiodic" };

export function geometry(inst) {
  const n = inst.n_sites;
  if (/^HEG/.test(inst.model)) return `${inst.lattice} cell, N = ${n}`;
  const cells = inst.lattice.match(/^([a-z]+)-(\d+(?:x\d+)+)$/);
  if (cells) {
    const product = cells[2].split("x").reduce((a, b) => a * Number(b), 1);
    return product === n ? `${cells[1]} ${cells[2]}` : `${cells[1]} ${cells[2]} (${n} sites)`;
  }
  const side = Math.sqrt(n);
  if (/^(square|triangular)$/.test(inst.lattice) && Number.isInteger(side))
    return `${inst.lattice} ${side}x${side}`;
  return `${inst.lattice}, ${n} sites`;
}

export function instanceLabel(inst) {
  if (inst.model === "Impurity") return `${inst.lattice}, size ${inst.n_sites}`;
  const p = inst.params ?? {};
  if (/^HEG/.test(inst.model))
    return [geometry(inst), `rs = ${p.rs}`, p.N_dn === 0 || p.N_up === 0 ? "polarized" : p.N_up === p.N_dn ? "unpolarized" : `N↑ = ${p.N_up}, N↓ = ${p.N_dn}`,
      ...(p.twist && p.twist !== "Gamma" ? [`twist ${p.twist}`] : [])].join(", ");
  const parts = [geometry(inst)];
  if (BOUNDARY[inst.boundary]) parts.push(BOUNDARY[inst.boundary]);
  for (const k of ["J2", "h", "U", "V"]) if (p[k] != null) parts.push(`${k} = ${p[k]}`);
  if (p.Nf != null) {
    // Filling per site. Hubbard files carry Nf = N_up = N_dn; t-V is spinless.
    const fill = (inst.model === "Hubbard" ? 2 * p.Nf : p.Nf) / inst.n_sites;
    const shown = Number(fill.toFixed(4));
    parts.push(`n ${shown === fill ? "=" : "&asymp;"} ${shown}`);
  }
  // The Hubbard variants VarBench names by suffix keep that name in the label; their couplings
  // (t2, V1, V2) are in params and written out on the instance page. Several t2 values share a
  // size, so a t12 label also states t2.
  for (const v of inst.instance_id.matchAll(/_(t12|UV1V2)(?=_|$)/g)) parts.push(v[1] === "t12" && p.t2 != null ? `t12 (t2 = ${p.t2})` : v[1]);
  return parts.join(", ");
}

export function byGeometry(a, b) {
  const key = i => [i.lattice, i.n_sites, i.boundary ?? "", i.params?.Nf ?? 0,
    i.params?.J2 ?? i.params?.h ?? i.params?.U ?? i.params?.V ?? 0, i.instance_id];
  const ka = key(a), kb = key(b);
  for (let k = 0; k < ka.length; k++) {
    if (ka[k] === kb[k]) continue;
    return typeof ka[k] === "number" ? ka[k] - kb[k] : ka[k].localeCompare(kb[k]);
  }
  return 0;
}

// Why an instance has no record, in the words the table prints. The test order is
// summary.mjs's (noRecordKey), so the cells agree with the totals under the table.
const NO_RECORD = {
  flagged: "every row that could hold it is flagged",
  sector_only: "exact rows are sector-resolved, no ground-state energy stated",
  unclassified: "no row has a bound_type yet",
  no_rows: "no row",
};
export function noRecordReason(inst) {
  return NO_RECORD[noRecordKey(inst)];
}

// The closest challenger: the lowest row above the record that could hold one itself
// (unflagged and not exact, of any other kind). On a solved instance that is the best
// non-exact energy anyone has published at or above the exact one.
export function challengerOf(inst, rec) {
  const sorted = [...inst.rows].sort((a, b) => a.energy - b.energy);
  return sorted.slice(sorted.indexOf(rec) + 1).find(recordEligible) ?? null;
}

// How far above the record the challenger sits, per site, to two figures: "+1.7e-3".
// Absolute, as the table is per site in the papers' convention. A gap under the record's
// quoted precision (DMRG converged to the exact energy at 1e-13) prints as below that
// precision.
export function gapAbove(rec, next, f, decimals) {
  const gap = (next.energy - rec.energy) / f;
  return gap < 10 ** -decimals ? `+<1e-${decimals}` : `+${gap.toExponential(1)}`;
}

// The code column links the code behind the record, where its source names one (DATA.md).
const HEADER = ["| instance | record | method | code | closest challenger |", "|---|---|---|---|---|"];

function row(inst, label, cache) {
  const rec = recordOf(inst);
  if (!rec) return `| ${label} | no record | ${noRecordReason(inst)} | | |`;
  const f = perSiteDivisor(inst) ?? 1;
  const q = quote(rec.energy / f, rec.sigma == null ? null : rec.sigma / f);
  const next = challengerOf(inst, rec);
  // Quoted at the record's precision so the two are readable against each other, with
  // the same markers the record cell uses and the gap above the record spelled out.
  // Each method carries its own source link, so the challenger is as checkable as the
  // record.
  const challenger = next
    ? `${(next.energy / f).toFixed(q.decimals)}${marks(next)} (${gapAbove(rec, next, f, q.decimals)}) ${shorten(methodLabel(next), 34)} ${citeCell(next, cache)}`
    : "none";
  return `| ${label} | **${q.text}**${marks(rec)}${stochasticExact(rec) ? " exact (stochastic)" : ""} | ${shorten(methodLabel(rec), 46)} ${citeCell(rec, cache)} | ${codeCell(rec)} | ${challenger} |`;
}

function main() {
  const instances = collect();
  const s = summarize(instances);
  const cache = sources();

  const lines = [];
  lines.push(`### All ${s.instances} Hamiltonian instances (click a model to expand)`);
  lines.push("");
  const known = new Set(MODELS.map(([m]) => m));
  for (const inst of instances)
    if (!known.has(inst.model)) throw new Error(`${inst.instance_id}: model ${inst.model} has no MODELS entry`);
  for (const [model, name] of MODELS) {
    const group = instances.filter(i => i.model === model).sort(byGeometry);
    if (!group.length) continue;
    // GitHub only renders a table inside <details> when a blank line follows <summary>.
    lines.push("<details>");
    lines.push(`<summary><b>${name}</b>: ${group.length} instances, energies as <code>${perSiteLabel(group[0])}</code></summary>`);
    lines.push("", ...HEADER, ...group.map(i => row(i, instanceLabel(i), cache)), "", "</details>", "");
  }

  // The legend (bound_type, bold, circle, dagger) is in the hand-written "## Details" section
  // below the END marker, so the generator emits nothing after the last </details>; the
  // table-wide counts are in data/_summary.json and on the site's front page.

  let readme = fs.readFileSync("README.md", "utf8");
  const rows = instances.flatMap(inst => inst.rows);
  const imported = rows.filter(r => r.provenance === "imported" && String(r.source).startsWith("varbench")).length;
  const vm = readme.match(VB_COUNT);
  if (!vm || readme.match(new RegExp(VB_COUNT, "g")).length !== 1) throw new Error("README.md: the VarBench row count must occur exactly once");
  // Spliced by index, never by String.replace (see below).
  readme = readme.slice(0, vm.index)
    + `${imported} of QMBL’s ${rows.length} rows (${Math.round(100 * imported / rows.length)} %)`
    + readme.slice(vm.index + vm[0].length);
  const i = readme.indexOf(BEGIN);
  const j = readme.indexOf(END);
  if (i < 0 || j < 0) throw new Error("README.md is missing the leaderboard markers");
  // Spliced by index, never by String.replace: a replacement containing $' or $& is
  // interpreted as a match reference and pastes the file back into itself.
  const block = `${BEGIN}\n\n${lines.join("\n").trimEnd()}\n\n${END}`;
  fs.writeFileSync("README.md", readme.slice(0, i) + block + readme.slice(j + END.length));
  console.log(`README.md leaderboard: ${s.instances} instances by model, ${s.records.held}/${s.instances} records held; ${imported} rows imported from VarBench`);
}

